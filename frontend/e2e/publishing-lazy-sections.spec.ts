import {test,expect} from '@playwright/test';
for(const width of [390,1280])test(`publishing fetches unopened sections only on demand at ${width}px`,async({page},info)=>{
 const reads:string[]=[],writes:string[]=[];let variantsFail=false;
 await page.route('**/*',async r=>{const u=new URL(r.request().url()),p=u.pathname;
 if(!p.startsWith('/api/')&&!p.startsWith('/posts')&&!p.startsWith('/schedules'))return r.continue();
 if(r.request().method()!=='GET')writes.push(p);else reads.push(p);
 if(p==='/api/artifacts/platform-variants')return r.fulfill(variantsFail?{status:503,json:{detail:'offline'}}:{json:[]});
 if(p==='/posts/filter-options')return r.fulfill({json:{sources:[],kinds:[]}});
 if(p==='/api/platform-operations')return r.fulfill({json:{items:[],total:0,counts:{waiting:0,published:22,attention:0,total:23}}});
 return r.fulfill({json:{items:[],total:p==='/schedules'?24:0}});
 });
 await page.setViewportSize({width,height:900});await page.goto('/publishing?view=plans');
 await expect(page.getByTestId('publishing-plans')).toBeVisible();
 await expect(page.getByRole('button',{name:/خطط النشر/}).first()).toContainText('24');
 await expect(page.getByRole('button',{name:/نشر Meta المؤكد/})).toContainText('22');
 for(const p of ['/posts','/posts/filter-options','/api/artifacts','/api/artifacts/platform-variants','/schedules/calendar'])expect(reads,p).not.toContain(p);
 expect(reads.slice().sort()).toEqual(['/api/platform-operations','/schedules','/schedules/upcoming'].sort());
 await expect(page.getByRole('button',{name:/مسودات المنصات/})).toContainText('—');
 await page.getByRole('button',{name:/نشر Meta المؤكد/}).click();await expect(page.getByTestId('publishing-operations')).toBeVisible();
 expect(reads).not.toContain('/schedules/calendar');expect(reads).not.toContain('/posts');
 await page.getByRole('button',{name:/التقويم · كل المنصات/}).click();
 await expect.poll(()=>reads.includes('/schedules/calendar')).toBeTruthy();
 await expect(page.getByTestId('publishing-calendar')).toBeVisible();
 await page.getByRole('button',{name:/مسودات المنصات/}).click();
 await expect(page.getByText('لا توجد مسودات منصات بعد',{exact:true})).toBeVisible();
 expect(reads).toContain('/api/artifacts/platform-variants');expect(reads).not.toContain('/posts');
 await page.getByRole('button',{name:/المحتوى والتجهيز/}).first().click();
 await expect(page.getByTestId('publishing-ready')).toBeVisible();expect(reads).not.toContain('/posts');
 await page.getByRole('button',{name:/جدولة نصوص Telegram/}).click();
 await expect(page.getByText('لا توجد منشورات جاهزة',{exact:true})).toBeVisible();
 for(const p of ['/posts','/posts/filter-options','/api/artifacts'])expect(reads).toContain(p);
 await page.goBack();await expect(page.getByTestId('publishing-ready')).toBeVisible();
 await page.goto('/publishing?view=calendar');await expect(page.getByTestId('publishing-calendar')).toBeVisible();
 await expect(page.getByLabel('تقويم Telegram المقسم')).toContainText('لا توجد عناصر Telegram لهذا اليوم');
 variantsFail=true;await page.goto('/publishing?view=platforms');
 await expect(page.getByRole('alert').filter({hasText:'تعذر تحميل مسودات المنصات'})).toBeVisible({timeout:15000});
 await expect(page.getByText('لا توجد مسودات منصات بعد',{exact:true})).toHaveCount(0);
 variantsFail=false;await page.getByRole('button',{name:'إعادة تحميل مسودات المنصات'}).click();
 await expect(page.getByText('لا توجد مسودات منصات بعد',{exact:true})).toBeVisible();
 await page.screenshot({path:info.outputPath(`lazy-sections-${width}.png`)});expect(writes).toEqual([]);
});
